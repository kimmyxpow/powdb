CREATE FUNCTION showcase.reports_of(p_manager integer)
RETURNS TABLE (id integer, full_name text, depth integer)
LANGUAGE sql STABLE AS $$
  WITH RECURSIVE r AS (
    SELECT e.id, e.full_name, 1 AS depth FROM showcase.employees e WHERE e.manager_id = p_manager
    UNION ALL
    SELECT e.id, e.full_name, r.depth + 1 FROM showcase.employees e JOIN r ON e.manager_id = r.id
  )
  SELECT * FROM r;
$$;
COMMENT ON FUNCTION showcase.reports_of(integer) IS 'Everyone reporting to a manager, directly or not';

CREATE FUNCTION showcase.format_amount(p_amount numeric) RETURNS text
LANGUAGE sql IMMUTABLE AS $$ SELECT to_char(p_amount, 'FM999G999G990D00') $$;
