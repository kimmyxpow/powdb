-- 3. a wide table (horizontal scrolling, column virtualisation) ------------
DO $$
DECLARE
  cols text := '';
BEGIN
  FOR i IN 1..60 LOOP
    cols := cols || format(', %I %s', 'col_' || lpad(i::text, 2, '0'),
      (ARRAY['integer', 'text', 'numeric(8,2)', 'boolean', 'date', 'jsonb'])[1 + (i - 1) % 6]);
  END LOOP;
  EXECUTE 'CREATE TABLE showcase.wide_table (id serial PRIMARY KEY' || cols || ')';
END
$$;
COMMENT ON TABLE showcase.wide_table IS '60 columns';

DO $$
DECLARE
  names text := '';
  vals  text := '';
BEGIN
  FOR i IN 1..60 LOOP
    names := names || format('%s%I', CASE WHEN i > 1 THEN ', ' END, 'col_' || lpad(i::text, 2, '0'));
