CREATE VIEW showcase.category_tree AS
WITH RECURSIVE tree AS (
  SELECT id, name, parent_id, name::text AS path, 0 AS depth FROM public.categories WHERE parent_id IS NULL
  UNION ALL
  SELECT c.id, c.name, c.parent_id, t.path || ' › ' || c.name, t.depth + 1
  FROM public.categories c JOIN tree t ON c.parent_id = t.id
)
SELECT * FROM tree ORDER BY path;
COMMENT ON VIEW showcase.category_tree IS 'Recursive CTE over public.categories';

CREATE MATERIALIZED VIEW showcase.department_stats AS
SELECT d.name AS department, count(e.id) AS headcount, round(avg(e.salary), 2) AS avg_salary,
       array_agg(DISTINCT e.country_code) AS countries
FROM showcase.departments d LEFT JOIN showcase.employees e ON e.department_id = d.id AND e.left_on IS NULL
GROUP BY d.name;

