CREATE FUNCTION showcase.raise_demo(p_level text DEFAULT 'notice') RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  RAISE NOTICE 'This is a notice';
  RAISE WARNING 'This is a warning';
  IF p_level = 'error' THEN
    RAISE EXCEPTION 'This is an error' USING HINT = 'Called with p_level = error', DETAIL = 'Raised on purpose';
  END IF;
END
$$;
COMMENT ON FUNCTION showcase.raise_demo(text) IS 'Emits NOTICE / WARNING messages, or an error';

